assert.equal(S.locationState({...session,expires_at:'2026-10-13T11:00:00Z'},now),'ended');
assert.equal(S.locationState({...session,state:'ended'},now),'ended');
assert.equal(S.locationState({...session,updated_at:'bad'},now),'stale');
